// ==================================================
// BACKWARD COMPATIBILITY HELPER
// ==================================================
export function normalizeCategoryLabel(category: string): string {
  if (!category || category === '-- เลือกหมวดหมู่หลัก --') {
    return category;
  }
  const normalized = CATEGORY_NORMALIZATION_MAP[category] || category;
  // Ensure it's a valid main category
  if (MAIN_CATEGORIES.includes(normalized as any)) {
    return normalized;
  }
  // Fallback to original if not found
  return category;
}

// Get subcategories for a given main category
export function getSubcategoriesForCategory(category: string): string[] {
  const normalized = normalizeCategoryLabel(category);
  return SUBCATEGORIES_MAP[normalized] || [];
}

